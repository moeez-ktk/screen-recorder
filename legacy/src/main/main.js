/** Pull `--cmd=<name>` out of an argv, which is how the listener starts us. */
function commandFromArgv(argv) {
  const arg = (argv || []).find(a => typeof a === 'string' && a.startsWith('--cmd='));
  return arg ? arg.slice('--cmd='.length).trim() : null;
}

let commandServer = null;

if (!app.requestSingleInstanceLock()) {
  app.quit();
} else {
  // A second launch means the listener could not reach our pipe (we were
  // still starting up). Honour the command instead of just showing the UI.
  app.on('second-instance', (_e, argv) => {
    cancelExit();
    const cmd = commandFromArgv(argv);
    if (cmd) runCommand(cmd);
    else createOverlay().showInactive();
  });

  app.whenReady().then(async () => {
    settings.init();

    // Auto-answer getDisplayMedia in our hidden audio window: we only want the
    // loopback audio track, so grant the first screen and take 'loopback'.
    session.defaultSession.setDisplayMediaRequestHandler(async (request, callback) => {
      try {
        const list = await desktopCapturer.getSources({ types: ['screen'], thumbnailSize: { width: 0, height: 0 } });
        callback({ video: list[0], audio: 'loopback' });
      } catch (_) {
        callback({});
      }
    }, { useSystemPicker: false });

    session.defaultSession.setPermissionRequestHandler((_wc, permission, cb) => {
      cb(permission === 'media' || permission === 'audioCapture');
    });

    currentSource = sources.defaultSource();

    wireIpc();
    wireRecorderEvents();
    wireBridge();
    createTray();
    createOverlay();

    commandServer = startCommandServer();
    writeListenerConfig();

    encoderInfo = await encoders.detect(settings.get('ffmpegPath'));
    if (!encoderInfo.ffmpeg) {
      toast('ffmpeg was not found - set its path in Settings before recording.', 'warn');
    }
    pushState();

    // If the listener started us to do something specific, do it now that
    // encoder detection has finished.
    const cmd = commandFromArgv(process.argv);
    if (cmd && cmd !== 'launch' && cmd !== 'toggleOverlay') runCommand(cmd);
  });

  // Closing the last window must not quit on its own; maybeQuit() decides,
  // so that a recording in progress is never cut short.
  app.on('window-all-closed', () => { maybeQuit(); });

  app.on('will-quit', () => {
    cancelExit();
    try { if (commandServer) commandServer.close(); } catch (_) {}
  });

  app.on('before-quit', async e => {
    if (isRecording()) {
      e.preventDefault();
      await stopRecording();
      app.exit(0);
      return;
    }
    try { await audioSessions.restoreAll(); } catch (_) {}
    audioSessions.shutdown();
    if (bridge) { bridge.restoreTabMutes(); bridge.stop(); }
  });
}
